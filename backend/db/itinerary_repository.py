from typing import Optional, Union

from models.schemas import DayPlan, ItineraryResponse, TripRequest

from db.schema_guard import get_verified_client


def _plan_payload(itinerary: ItineraryResponse) -> list:
    return [day.model_dump() for day in itinerary.plan]


def _from_row(row: dict) -> ItineraryResponse:
    trip = row.get("trips") or {}
    plan_rows = row.get("plan") or row.get("itinerary") or []
    plan = [DayPlan(**item) for item in plan_rows]
    itin_id = int(row.get("id") or 0)
    raw_trip_id = row.get("trip_id")
    trip_id = int(raw_trip_id) if raw_trip_id is not None else None
    return ItineraryResponse(
        id=itin_id,
        trip_id=trip_id,
        destination=trip.get("destination") or "",
        days=int(trip.get("days") or 0),
        summary=row.get("summary") or "",
        provider=row.get("provider") or "mock",
        plan=plan,
    )


def save_itinerary(trip: TripRequest, itinerary: ItineraryResponse) -> bool:
    """Insert trip + itinerary using numeric BIGINT IDs generated by Supabase."""
    client = get_verified_client()
    if client is None:
        return False

    # 1. Insert trip record and let PostgreSQL assign BIGINT id
    trip_payload = {
        "destination": trip.destination,
        "days": trip.days,
        "budget": trip.budget,
        "interests": trip.interests,
        "traveler_type": trip.traveler_type,
    }
    trip_result = client.table("trips").insert(trip_payload).execute()
    if not trip_result.data:
        return False

    db_trip_id = int(trip_result.data[0]["id"])
    itinerary.trip_id = db_trip_id

    # 2. Insert itinerary referencing the assigned db_trip_id
    plan_data = _plan_payload(itinerary)
    itin_payload = {
        "trip_id": db_trip_id,
        "provider": itinerary.provider,
        "summary": itinerary.summary,
        "plan": plan_data,
        "itinerary": plan_data,  # Satisfies legacy NOT NULL json column in Supabase
    }
    itin_result = client.table("itineraries").insert(itin_payload).execute()
    if not itin_result.data:
        return False

    db_itin_id = int(itin_result.data[0]["id"])
    itinerary.id = db_itin_id
    return True


def fetch_itinerary(itinerary_id: Union[int, str]) -> Optional[ItineraryResponse]:
    """Retrieve an itinerary by its numeric BIGINT ID."""
    client = get_verified_client()
    if client is None:
        return None

    try:
        parsed_id = int(itinerary_id)
    except (ValueError, TypeError):
        return None

    result = (
        client.table("itineraries")
        .select("id,provider,summary,plan,itinerary,trip_id,trips(destination,days)")
        .eq("id", parsed_id)
        .limit(1)
        .execute()
    )
    rows = result.data or []
    if not rows:
        return None
    return _from_row(rows[0])


def fetch_latest_itinerary() -> Optional[ItineraryResponse]:
    """Retrieve the most recently created itinerary."""
    client = get_verified_client()
    if client is None:
        return None

    result = (
        client.table("itineraries")
        .select("id,provider,summary,plan,itinerary,trip_id,trips(destination,days)")
        .order("id", desc=True)
        .limit(1)
        .execute()
    )
    rows = result.data or []
    if not rows:
        return None
    return _from_row(rows[0])

