import React, { useState } from "react";
import {
  CalendarIcon,
  SparklesIcon,
  WalletIcon,
  ArrowLeftIcon,
  CopyIcon,
  PrinterIcon,
  CheckCircleIcon,
  MapPinIcon,
} from "./Icons.jsx";
import { getDestinationImage } from "../utils/destinations.js";

export default function ItineraryCard({
  itinerary,
  onNavigateHome,
  onPlanNew,
}) {
  const [copied, setCopied] = useState(false);
  const [completedActivities, setCompletedActivities] = useState({});

  if (!itinerary) {
    return (
      <div className="empty-itinerary-card">
        <div className="empty-icon-wrap">
          <MapPinIcon size={40} />
        </div>
        <h3>No Itinerary Selected</h3>
        <p>
          You haven't generated or selected an itinerary yet. Plan a new trip or choose
          one from your saved collection.
        </p>
        <button
          type="button"
          className="primary btn-start-planning"
          onClick={() => onPlanNew && onPlanNew()}
        >
          <SparklesIcon size={16} />
          <span>Plan a New Trip</span>
        </button>
      </div>
    );
  }

  const destinationPhoto = getDestinationImage(itinerary.destination);

  function handleCopySummary() {
    const text = `Travel Itinerary for ${itinerary.destination} (${itinerary.days} Days)\n\n${itinerary.summary}\n\nGenerated by ${itinerary.provider} (ID: ${itinerary.id})`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2200);
  }

  function handlePrint() {
    window.print();
  }

  function toggleActivity(key) {
    setCompletedActivities((prev) => ({
      ...prev,
      [key]: !prev[key],
    }));
  }

  return (
    <article className="itinerary-details-view">
      {/* Top action toolbar (hidden on print) */}
      <div className="itinerary-toolbar no-print">
        <button
          type="button"
          className="toolbar-btn secondary"
          onClick={() => onNavigateHome && onNavigateHome()}
        >
          <ArrowLeftIcon size={16} />
          <span>Back to Dashboard</span>
        </button>

        <div className="toolbar-actions-right">
          <button
            type="button"
            className="toolbar-btn secondary"
            onClick={handleCopySummary}
            title="Copy summary to clipboard"
          >
            <CopyIcon size={16} />
            <span>{copied ? "Copied!" : "Copy Summary"}</span>
          </button>

          <button
            type="button"
            className="toolbar-btn secondary"
            onClick={handlePrint}
            title="Print or export as PDF"
          >
            <PrinterIcon size={16} />
            <span>Print Itinerary</span>
          </button>

          <button
            type="button"
            className="toolbar-btn primary"
            onClick={() => onPlanNew && onPlanNew()}
          >
            <SparklesIcon size={16} />
            <span>Plan Another Trip</span>
          </button>
        </div>
      </div>

      {/* Hero Destination Banner */}
      <div className="itinerary-hero-banner">
        <img
          src={destinationPhoto}
          alt={itinerary.destination}
          className="itinerary-hero-img"
          onError={(e) => {
            e.currentTarget.src =
              "https://images.unsplash.com/photo-1469854523086-cc02fe5d8800?auto=format&fit=crop&w=1200&q=80";
          }}
        />
        <div className="itinerary-hero-gradient-overlay" />

        <div className="itinerary-hero-content">
          <div className="itinerary-hero-badges">
            <span className="badge-pill hero-ai-badge">
              <SparklesIcon size={14} />
              <span>
                {itinerary.provider === "gemini" ? "Gemini AI" : itinerary.provider}
              </span>
            </span>
            <span className="badge-pill hero-duration-badge">
              <CalendarIcon size={14} />
              <span>{itinerary.days} {itinerary.days === 1 ? "Day" : "Days"}</span>
            </span>
            {itinerary.id && (
              <span className="badge-pill hero-id-badge">
                Trip ID #{itinerary.id}
              </span>
            )}
          </div>

          <h1 className="itinerary-hero-title">{itinerary.destination}</h1>
          <p className="itinerary-hero-summary">{itinerary.summary}</p>
        </div>
      </div>

      {/* Meta Info Bar */}
      <div className="itinerary-meta-strip">
        <div className="meta-strip-item">
          <span className="meta-label">Destination</span>
          <span className="meta-value">{itinerary.destination}</span>
        </div>
        <div className="meta-strip-item">
          <span className="meta-label">Total Duration</span>
          <span className="meta-value">{itinerary.days} Days / {Math.max(1, itinerary.days - 1)} Nights</span>
        </div>
        <div className="meta-strip-item">
          <span className="meta-label">AI Generation</span>
          <span className="meta-value capitalize">{itinerary.provider}</span>
        </div>
        <div className="meta-strip-item">
          <span className="meta-label">Status</span>
          <span className="meta-value status-saved-badge">✓ Saved to Cloud</span>
        </div>
      </div>

      {/* Day by Day Itinerary Schedule */}
      <section className="itinerary-timeline-section" aria-label="Daily Schedule">
        <div className="timeline-section-header">
          <h2 className="timeline-title">Day-by-Day Experience</h2>
          <span className="timeline-subtitle">
            {itinerary.plan ? itinerary.plan.length : 0} scheduled days
          </span>
        </div>

        <div className="daily-cards-container">
          {itinerary.plan?.map((dayPlan, index) => {
            const dayNum = dayPlan.day || index + 1;
            return (
              <div className="day-card" key={`day-${dayNum}`}>
                <div className="day-card-header">
                  <div className="day-number-badge">
                    <span className="day-label">DAY</span>
                    <span className="day-val">{dayNum}</span>
                  </div>

                  <div className="day-title-wrap">
                    <h3 className="day-headline">{dayPlan.title}</h3>
                    {dayPlan.estimated_cost && (
                      <span className="day-cost-badge">
                        <WalletIcon size={14} />
                        <span>Est: {dayPlan.estimated_cost}</span>
                      </span>
                    )}
                  </div>
                </div>

                <div className="day-activities-list">
                  {dayPlan.activities?.map((activity, actIdx) => {
                    const activityKey = `d${dayNum}-a${actIdx}`;
                    const isChecked = !!completedActivities[activityKey];

                    // Determine suggested time or stage badge
                    let timeLabel = `Activity ${actIdx + 1}`;
                    let activityContent = activity;

                    // If text contains "Morning:", "Afternoon:", "Evening:", parse nicely
                    const colonMatch = activity.match(/^(Morning|Afternoon|Evening|Night|Late Evening|Breakfast|Lunch|Dinner):\s*(.*)$/i);
                    if (colonMatch) {
                      timeLabel = colonMatch[1];
                      activityContent = colonMatch[2];
                    } else if (dayPlan.activities.length === 3) {
                      if (actIdx === 0) timeLabel = "Morning";
                      else if (actIdx === 1) timeLabel = "Afternoon";
                      else if (actIdx === 2) timeLabel = "Evening";
                    }

                    return (
                      <div
                        key={actIdx}
                        className={`activity-item ${isChecked ? "completed" : ""}`}
                        onClick={() => toggleActivity(activityKey)}
                        role="checkbox"
                        aria-checked={isChecked}
                        tabIndex={0}
                        onKeyDown={(e) => {
                          if (e.key === " " || e.key === "Enter") {
                            e.preventDefault();
                            toggleActivity(activityKey);
                          }
                        }}
                      >
                        <div className="activity-checkbox">
                          {isChecked ? (
                            <CheckCircleIcon size={20} className="check-done" />
                          ) : (
                            <div className="checkbox-empty" />
                          )}
                        </div>

                        <div className="activity-details">
                          <span className="activity-time-pill">{timeLabel}</span>
                          <p className="activity-text">{activityContent}</p>
                        </div>
                      </div>
                    );
                  })}
                </div>
              </div>
            );
          })}
        </div>
      </section>

      {/* Footer Return Action (no-print) */}
      <div className="itinerary-footer-actions no-print">
        <button
          type="button"
          className="secondary btn-footer-back"
          onClick={() => onNavigateHome && onNavigateHome()}
        >
          <ArrowLeftIcon size={16} />
          <span>Return to Dashboard</span>
        </button>
        <button
          type="button"
          className="primary btn-footer-new"
          onClick={() => onPlanNew && onPlanNew()}
        >
          <SparklesIcon size={16} />
          <span>Plan a Different Trip</span>
        </button>
      </div>
    </article>
  );
}
